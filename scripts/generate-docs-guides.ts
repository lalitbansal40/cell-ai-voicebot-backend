import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import * as prettier from 'prettier';

import { GUIDE_ORDER } from '../src/modules/docs/guides';

/**
 * Copies `docs/api/*.md` into `src/modules/docs/guides.gen.ts` (committed), so the
 * docs page works from the compiled image without reading the repo's docs folder.
 * `tests/docs/guides.test.ts` fails when the two differ.
 */
export const renderGuidesModule = async (root: string): Promise<string> => {
  const files = Object.fromEntries(
    GUIDE_ORDER.map((name) => [
      name,
      readFileSync(path.join(root, 'docs', 'api', `${name}.md`), 'utf8'),
    ]),
  );
  const outFile = path.join(root, 'src', 'modules', 'docs', 'guides.gen.ts');
  const source = `// Generated by \`npm run gen:guides\` from docs/api/*.md — do not edit.\nexport const GUIDE_FILES: Record<string, string> = ${JSON.stringify(files)};\n`;
  const options = (await prettier.resolveConfig(outFile)) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
};

const main = async (): Promise<void> => {
  const root = path.resolve(__dirname, '..');
  const outFile = path.join(root, 'src', 'modules', 'docs', 'guides.gen.ts');
  writeFileSync(outFile, await renderGuidesModule(root));
  console.info(`Guides written to ${path.relative(process.cwd(), outFile)}`);
};

if (require.main === module) {
  main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
  });
}
