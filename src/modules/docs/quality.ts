import { API_KEY_SCOPES } from '../api-keys/scopes';

import type { OpenApiDoc } from './public-spec';

/**
 * Rules every public operation follows (PUBLIC_API_DOCS_PROMPT L5): an operationId,
 * a real description, the API key scope, examples and the common error answers.
 * Used by `npm run docs:audit` and `tests/docs/public-spec-quality.test.ts`.
 */

export interface OpAudit {
  method: string;
  path: string;
  operationId: string | null;
  scope: string | null;
  descriptionChars: number;
  requestExample: boolean | null;
  responseExample: boolean;
  errors: string[];
  tags: string[];
  problems: string[];
}

const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;
const SCOPES = new Set<string>(API_KEY_SCOPES);

type Op = Record<string, unknown> & {
  operationId?: string;
  description?: string;
  tags?: string[];
  requestBody?: { content?: Record<string, { example?: unknown; examples?: unknown }> };
  responses?: Record<
    string,
    { content?: Record<string, { example?: unknown; examples?: unknown }> }
  >;
  'x-scope'?: string | string[];
};

const hasExample = (
  content: Record<string, { example?: unknown; examples?: unknown }> | undefined,
) => Object.values(content ?? {}).some((c) => c.example !== undefined || c.examples !== undefined);

export const auditPublicSpec = (spec: OpenApiDoc): OpAudit[] => {
  const out: OpAudit[] = [];
  const seenIds = new Map<string, string>();
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const op = item[method] as Op | undefined;
      if (!op) continue;
      const problems: string[] = [];
      const name = `${method.toUpperCase()} ${path}`;
      const id = op.operationId ?? null;
      if (!id) problems.push('no operationId');
      else if (!/^[a-z][A-Za-z0-9]+$/.test(id)) problems.push('operationId not camelCase');
      else if (seenIds.has(id)) problems.push(`operationId also on ${seenIds.get(id) ?? ''}`);
      if (id) seenIds.set(id, name);
      const scopes = op['x-scope'] === undefined ? [] : ([] as string[]).concat(op['x-scope']);
      const whoami = path === '/api/v1/api-keys/whoami';
      if (!whoami && !scopes.length) problems.push('no x-scope');
      for (const s of scopes) if (!SCOPES.has(s)) problems.push(`unknown scope ${s}`);
      const description = op.description ?? '';
      if (description.trim().length < 40) problems.push('description shorter than 40 chars');
      const hasBody = Boolean(op.requestBody);
      const requestExample = hasBody ? hasExample(op.requestBody?.content) : null;
      if (hasBody && !requestExample) problems.push('no request example');
      const responses = op.responses ?? {};
      const success = Object.entries(responses).filter(([code]) => /^2\d\d$/.test(code));
      const responseExample = success.some(([, r]) => hasExample(r.content) || !r.content);
      if (!responseExample) problems.push('no 2xx example');
      const errors = Object.keys(responses).filter((c) => /^[45]\d\d$/.test(c));
      const needed = ['401', '403', '422', '429', ...(path.includes('{') ? ['404'] : [])];
      for (const code of needed) if (!errors.includes(code)) problems.push(`no ${code} response`);
      out.push({
        method: method.toUpperCase(),
        path,
        operationId: id,
        scope: scopes.join(', ') || null,
        descriptionChars: description.trim().length,
        requestExample,
        responseExample,
        errors,
        tags: op.tags ?? [],
        problems,
      });
    }
  }
  return out;
};

