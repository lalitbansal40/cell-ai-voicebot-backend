export const auditMarkdown = (rows: OpAudit[]): string => {
  const yes = (v: boolean | null) => (v === null ? '—' : v ? '✓' : '✗');
  const lines = [
    '# Public API audit',
    '',
    'Generated by `npm run docs:audit` — do not edit.',
    '',
    `Operations: ${String(rows.length)} · with problems: ${String(rows.filter((r) => r.problems.length).length)}`,
    '',
    '| Method | Path | operationId | Scope | Desc | Req ex | 2xx ex | Errors | Problems |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| ${r.method} | \`${r.path}\` | ${r.operationId ?? '—'} | ${r.scope ?? '—'} | ${String(r.descriptionChars)} | ${yes(r.requestExample)} | ${yes(r.responseExample)} | ${r.errors.join(' ')} | ${r.problems.join('; ') || '—'} |`,
    ),
    '',
  ];
  return lines.join('\n');
};
