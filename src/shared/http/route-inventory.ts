import type { Express } from 'express';

export interface RouteRow {
  method: string;
  path: string;
  /** A sign-in or key is checked on this route. */
  authenticated: boolean;
  /** A limiter of its own, besides the global one. */
  limited: boolean;
}

interface Layer {
  handle: {
    stack?: Layer[];
    getKey?: unknown;
    isAuthGuard?: boolean;
    isGlobalLimiter?: boolean;
  };
  matchers: ((path: string) => false | { path: string })[];
  /** Mounted at `/`: consumes nothing. */
  slash?: boolean;
  route?: { methods: Record<string, boolean>; stack: Layer[] };
}

const isLimiter = (layer: Layer) =>
  typeof layer.handle.getKey === 'function' && !layer.handle.isGlobalLimiter;
const isAuth = (layer: Layer) => layer.handle.isAuthGuard === true;

interface Guard {
  authenticated: boolean;
  limited: boolean;
}

/** Follows one request through the routers, as Express would, noting the guards it passes. */
const trace = (stack: Layer[], method: string, path: string, guard: Guard): Guard | null => {
  const state = { ...guard };
  for (const layer of stack) {
    const match = layer.slash ? { path: '' } : layer.matchers.map((m) => m(path)).find(Boolean);
    if (!match) continue;
    if (layer.route) {
      if (!layer.route.methods[method]) continue;
      return {
        authenticated: state.authenticated || layer.route.stack.some(isAuth),
        limited: state.limited || layer.route.stack.some(isLimiter),
      };
    }
    if (layer.handle.stack) {
      const rest = path.slice(match.path.length) || '/';
      const found = trace(layer.handle.stack, method, rest, state);
      if (found) return found;
      // a router with no such route: its own middleware still ran
      state.authenticated ||= layer.handle.stack.some((l) => !l.route && isAuth(l));
      continue;
    }
    if (isAuth(layer)) state.authenticated = true;
    if (isLimiter(layer)) state.limited = true;
  }
  return null;
};

/** How each documented route is guarded in this app. A route it can't reach is left out. */
export const listRoutes = (
  app: Express,
  routes: { method: string; path: string }[],
): RouteRow[] => {
  const stack = (app as unknown as { router: { stack: Layer[] } }).router.stack;
  return routes.flatMap(({ method, path }) => {
    const concrete = path.replace(/\{[^}]+\}/g, 'x');
    const guard = trace(stack, method, concrete, { authenticated: false, limited: false });
    return guard ? [{ method: method.toUpperCase(), path, ...guard }] : [];
  });
};

/** `docs/security/RATE_LIMITS.md`, so the file and the code can't drift apart. */
export const renderRateLimits = (rows: RouteRow[], exempt: Record<string, string>): string => {
  const open = rows.filter((r) => !r.authenticated);
  const limited = rows.filter((r) => r.authenticated && r.limited);
  const line = (r: RouteRow) => `\`${r.method} ${r.path}\``;
  return `${[
    '# Rate limits',
    '',
    'Generated by `npm run gen:rate-limits`. `tests/security/rate-limits.test.ts` fails when this file is out of date, or when a route with no sign-in has neither a limiter nor a reason here.',
    '',
    'Every request also passes the global limit of 1,200 a minute per IP. API keys have per-key limits: 600 reads and 60 writes a minute by default.',
    '',
    '## Routes with no sign-in',
    '',
    ...open.map((r) =>
      r.limited
        ? `- ${line(r)}: own limiter`
        : `- ${line(r)}: no limiter. ${exempt[`${r.method} ${r.path}`] ?? ''}`,
    ),
    '',
    '## Signed-in routes with their own limiter',
    '',
    ...limited.map((r) => `- ${line(r)}`),
  ].join('\n')}\n`;
};
